"""Cache busting by content hash, so browsers and CDNs never mix old and new files after an update.
- index.html: ?v=<hash> on site-config.js, the CSS/JS, and every static assets/ reference (src, href, poster, srcset).
- assets/js/asset-versions.js: hashes of all media under assets/ that site.js loads by name (clips, film, posters, loops).
Run after changing any of those files:  python3 scripts/stamp_assets.py
"""
import hashlib, json, pathlib, re
root = pathlib.Path(__file__).resolve().parents[1]
def h(rel): return hashlib.sha256((root / rel).read_bytes()).hexdigest()[:8]
MEDIA = ("assets/video", "assets/media", "assets/hero", "assets/paper", "assets/social")
media = {}
for d in MEDIA:
    for f in sorted((root / d).rglob("*")):
        if f.is_file() and f.suffix.lower() in (".mp4", ".webm", ".jpg", ".jpeg", ".png", ".webp", ".vtt"):
            rel = f.relative_to(root).as_posix(); media[rel] = h(rel)
(root / "assets/js/asset-versions.js").write_text(
    "/* Generated by scripts/stamp_assets.py: content hashes for cache busting. Do not edit. */\n"
    "window.GNR_ASSET_V = " + json.dumps(media, separators=(",", ":"), sort_keys=True) + ";\n")
p = root / "index.html"; s = p.read_text()
def stamp(m):
    attr, path = m.group(1), m.group(2)
    if path.startswith('assets/fonts/') or not (root / path).is_file(): return m.group(0)  # fonts: must match the CSS url()
    return f'{attr}="{path}?v={h(path)}"'
s = re.sub(r'(href|src|poster|srcset)="((?:site-config\.js|assets/[^"?\s]+))(?:\?v=[0-9a-f]+)?"', stamp, s)
p.write_text(s); print("stamped", len(media), "media files")
